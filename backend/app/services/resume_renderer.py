
from typing import Any

from backend.app.models.resume_document import ResumeDocument


def _format_url(value: str) -> str | None:
    if not isinstance(value, str):
        return None

    url = value.strip()

    if url.startswith(("https://", "http://")):
        return url

    if (
        "." in url
        and " " not in url
        and "://" not in url
        and not url.startswith(("/", "#"))
    ):
        return "https://" + url

    return None


def render_resume_document(
    document: ResumeDocument,
    context: dict[str, Any],
) -> str:

    candidate = context["candidate"]

    work_lookup = {
        work["id"]: work
        for work in context["work_items"]
    }

    allowed_skills = {
        str(skill).strip().casefold()
        for skill in candidate.get("skills", [])
    }

    # Validate skill names against the master profile.
    for group in document.skill_groups:
        for skill in group.skills:
            if skill.strip().casefold() not in allowed_skills:
                raise ValueError(
                    f"Skill not found in profile: {skill}"
                )

    seen_work_ids = set()
    sections = {
        "experience": [],
        "project": [],
    }

    for entry in document.entries:
        if entry.work_id not in work_lookup:
            raise ValueError(
                f"Unknown work ID: {entry.work_id}"
            )

        if entry.work_id in seen_work_ids:
            raise ValueError(
                f"Duplicate work entry: {entry.work_id}"
            )

        seen_work_ids.add(entry.work_id)

        work = work_lookup[entry.work_id]

        allowed_fact_ids = {
            fact["id"]
            for fact in work["selected_facts"]
        }

        lines = []

        # Work metadata remains authoritative.
        if entry.section == "experience":
            heading = (
                work.get("organization")
                or work["name"]
            )
        else:
            heading = work["name"]

        role = work.get("role")

        if role and role.casefold() not in heading.casefold():
            heading += f" — {role}"

        lines.append(f"### {heading}")

        start = work.get("start_date")
        end = work.get("end_date")

        dates = " – ".join(
            str(value)
            for value in (start, end)
            if value
        )

        if dates:
            lines.append(f"*{dates}*")

        for bullet in entry.bullets:
            if bullet.fact_id not in allowed_fact_ids:
                raise ValueError(
                    "Fact does not belong to this work item: "
                    f"{bullet.fact_id} -> {entry.work_id}"
                )

            lines.append(f"- {bullet.text}")

        # Links are read only from existing profile metadata.
        links = work.get("links") or {}
        rendered_links = []

        if isinstance(links, dict):
            for label, raw_url in links.items():
                url = _format_url(raw_url)

                if url:
                    rendered_links.append(
                        f"[{str(label).replace('_', ' ').title()}]"
                        f"({url})"
                    )

        if rendered_links:
            lines.append(
                " | ".join(rendered_links[:2])
            )

        sections[entry.section].append(
            "\n".join(lines)
        )

    # Candidate identity is never generated by the LLM.
    output = [f"# {candidate['name']}"]

    output.append(f"**{document.headline}**")

    contact = []

    for key in ("email", "phone"):
        value = candidate.get(key)

        if value:
            contact.append(str(value))

    for key in ("github", "linkedin", "portfolio"):
        url = _format_url(candidate.get(key) or "")

        if url:
            contact.append(
                f"[{key.title()}]({url})"
            )

    if contact:
        output.append(" | ".join(contact))

    output.extend([
        "",
        "## Professional Summary",
        document.summary,
        "",
        "## Technical Skills",
    ])

    for group in document.skill_groups:
        skills = ", ".join(group.skills)

        output.append(
            f"- **{group.title}:** {skills}"
        )

    if sections["experience"]:
        output.extend([
            "",
            "## Professional Experience",
            "",
            "\n\n".join(sections["experience"]),
        ])

    if sections["project"]:
        output.extend([
            "",
            "## Selected Projects",
            "",
            "\n\n".join(sections["project"]),
        ])

    # Education always comes from the master profile.
    education = candidate.get("education") or []

    if isinstance(education, dict):
        education = [education]

    if education:
        output.extend([
            "",
            "## Education",
        ])

        for item in education:
            if not isinstance(item, dict):
                continue

            degree = item.get("degree")
            institution = item.get("institution")

            if degree:
                output.append(f"**{degree}**")

            if institution:
                output.append(str(institution))

            details = []

            if item.get("graduation_year"):
                details.append(
                    f"Graduation: {item['graduation_year']}"
                )

            if item.get("cgpa") is not None:
                details.append(
                    f"CGPA: {item['cgpa']}"
                )

            if details:
                output.append(" | ".join(details))

            output.append("")

    return "\n".join(output).strip()
